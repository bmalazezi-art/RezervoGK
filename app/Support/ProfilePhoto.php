<?php

namespace App\Support;

use Illuminate\Http\UploadedFile;
use Illuminate\Support\Facades\Storage;
use Illuminate\Support\Str;
use Illuminate\Validation\ValidationException;

class ProfilePhoto
{
    public static function rules(): array
    {
        return ['nullable', 'image', 'mimes:jpg,jpeg,png', 'max:5120', 'dimensions:max_width=3000,max_height=3000'];
    }

    public static function url(?string $path, string $fallback): string
    {
        // Resolve managed uploads against this deployment, not a historical origin.
        return $path && preg_match('/^keeper-photos\/[a-f0-9-]{36}\.(jpg|png)$/D', $path)
            ? Storage::disk('public')->url($path) : $fallback;
    }

    public function store(UploadedFile $file): string
    {
        $image = @imagecreatefromstring(file_get_contents($file->getRealPath()));
        if (! $image) {
            throw ValidationException::withMessages(['photo' => __('Fotografia nuk mund të lexohet.')]);
        }
        $jpeg = $file->getMimeType() === 'image/jpeg';
        try {
            // Preserve camera orientation while stripping EXIF and other uploaded metadata.
            if ($jpeg && function_exists('exif_read_data')) {
                $orientation = (@exif_read_data($file->getRealPath()))['Orientation'] ?? 1;
                if (in_array($orientation, [2, 4, 5, 7], true)) {
                    imageflip($image, in_array($orientation, [2, 5, 7], true) ? IMG_FLIP_HORIZONTAL : IMG_FLIP_VERTICAL);
                }
                $angle = match ($orientation) {
                    3 => 180, 5, 6 => -90, 7, 8 => 90, default => 0
                };
                if ($angle) {
                    $rotated = imagerotate($image, $angle, 0);
                    imagedestroy($image);
                    $image = $rotated;
                }
            }
            imagesavealpha($image, true);
            ob_start();
            try {
                $encoded = $jpeg ? imagejpeg($image, null, 88) : imagepng($image, null, 6);
                $bytes = ob_get_contents();
            } finally {
                ob_end_clean();
            }
        } finally {
            imagedestroy($image);
        }
        if (! $encoded || ! $bytes || strlen($bytes) > 5 * 1024 * 1024) {
            throw ValidationException::withMessages(['photo' => __('Fotografia duhet të jetë deri në 5MB pas përpunimit.')]);
        }
        $path = 'keeper-photos/'.Str::uuid().($jpeg ? '.jpg' : '.png');
        if (! Storage::disk('public')->put($path, $bytes)) {
            Storage::disk('public')->delete($path);
            throw ValidationException::withMessages(['photo' => __('Fotografia nuk u ruajt. Provo përsëri.')]);
        }

        return $path;
    }

    public function delete(?string $path): bool
    {
        // Only delete files generated by this service; never infer paths from public URLs.
        if ($path && preg_match('/^keeper-photos\/[a-f0-9-]{36}\.(jpg|png)$/D', $path)) {
            return Storage::disk('public')->delete($path);
        }

        return true;
    }
}
